#Requires -Version 7
<#
.SYNOPSIS
    Installs everything a fresh checkout needs to build and test Anbot on Windows.

.DESCRIPTION
    Mirrors scripts/setup.sh for Windows (PowerShell 7). Installs from the lockfiles:
      ds-bot/node_modules   build tools (esbuild) for client.js and link.js
      link/node_modules     phone link packages
      ds-bot/dev/harness    DSH packages for the unit tests and linter (skip with -WithoutHarness)
      app/node_modules      desktop app packages (skip with -PluginOnly)
    Then regenerates ds-bot/client.js and ds-bot/link.js and verifies client.js matches src/client.

    Requirements: Node.js 22.19 or later (Node 24 recommended), npm 11 or later, Git. The app
    lockfile was generated by npm 11; npm 10 rejects it as out of sync. Native test dependencies
    (node-pty, koffi) need the Visual Studio Build Tools (C++ desktop development) and Python 3
    if they are compiled from source.

    NOTE: this script has not been run on a real Windows machine in this environment; the
    windows-latest job in .github/workflows/setup.yml is the Windows verification.

.PARAMETER PluginOnly
    Skip the desktop app's dependencies (plugin/DSH usage only).

.PARAMETER WithoutHarness
    Skip the DSH test harness packages in ds-bot/dev/harness.
#>
[CmdletBinding()]
param(
    [switch]$PluginOnly,
    [switch]$WithoutHarness
)

$ErrorActionPreference = 'Stop'

function Fail {
    param([string]$Message)
    Write-Error "setup: $Message"
    exit 1
}

function Invoke-Npm {
    param([string]$Directory, [string[]]$Arguments)
    Push-Location $Directory
    try {
        & $npm @Arguments
        if ($LASTEXITCODE -ne 0) { throw "npm $($Arguments -join ' ') failed (exit $LASTEXITCODE)." }
    } finally {
        Pop-Location
    }
}

$node = Get-Command node -ErrorAction SilentlyContinue
if (-not $node) { Fail "Node.js is not installed or not on PATH. Install Node.js 22.19 or later (Node 24 recommended), for example with nvm-windows or fnm, then re-run this script." }
$npm = Get-Command npm.cmd -ErrorAction SilentlyContinue
if (-not $npm) { $npm = Get-Command npm -ErrorAction SilentlyContinue }
if (-not $npm) { Fail "npm is not installed or not on PATH. It ships with Node.js; reinstall Node.js 22.19 or later." }
if (-not (Get-Command git -ErrorAction SilentlyContinue)) { Fail "Git is not installed or not on PATH." }

$nodeVersion = [version](node -p 'process.versions.node')
$npmVersion = (& $npm.Source -v).Trim()
$npmMajor = [int]($npmVersion.Split('.')[0])

$nodeFloor = [version]'22.19.0'
if ($nodeVersion -lt $nodeFloor) {
    Fail "Node $nodeVersion is too old. This checkout needs Node.js 22.19 or later (Node 24 recommended); switch with nvm-windows/fnm and re-run."
}
if ($npmMajor -lt 11) {
    Fail "npm $npmVersion is too old. The app lockfile was generated by npm 11: upgrade Node.js to 24 (which ships npm 11), or run 'npm install -g npm@11', then re-run."
}

if ($nodeVersion.Major -eq 22) {
    Write-Host "setup: note: Node 22 is supported by CI; the pinned DSH runtime declares Node >=24.9.0 and prints an EBADENGINE warning on Node 22."
}

# Windows toolchain hints. These warn only: unit tests can run without native compilation, but a
# missing C++ toolchain surfaces later as a node-pty / koffi build failure.
if (-not (Get-Command cl.exe -ErrorAction SilentlyContinue)) {
    Write-Warning "setup: no Visual Studio C++ compiler on PATH. If a native module fails to build, install the 'Desktop development with C++' workload from the Visual Studio Build Tools."
}
if (-not (Get-Command python -ErrorAction SilentlyContinue) -and -not (Get-Command python3 -ErrorAction SilentlyContinue)) {
    Write-Warning "setup: Python 3 is missing; node-gyp needs it. Install Python 3 from python.org or the Microsoft Store if a native module compiles from source."
}

$root = [IO.Path]::GetFullPath((git rev-parse --show-toplevel))
Set-Location $root

Write-Host "setup: ds-bot build tools"
try { Invoke-Npm -Directory (Join-Path $root 'ds-bot') -Arguments @('ci', '--no-fund', '--no-audit') }
catch { Fail "ds-bot npm ci failed. Check the npm/registry output above; a proxy or mirror issue usually shows here." }

Write-Host "setup: phone link packages"
try { Invoke-Npm -Directory (Join-Path $root 'link') -Arguments @('ci', '--no-fund', '--no-audit') }
catch { Fail "link npm ci failed. Check the npm/registry output above." }

Write-Host "setup: regenerate client.js and link.js"
try { Invoke-Npm -Directory (Join-Path $root 'ds-bot') -Arguments @('run', 'build') }
catch { Fail "ds-bot build failed (esbuild). Re-run after fixing the reported src/client or src/link error." }

if ($WithoutHarness) {
    Write-Host "setup: skipping DSH test harness (-WithoutHarness)"
} else {
    Write-Host "setup: DSH test harness packages"
    try { Invoke-Npm -Directory (Join-Path $root 'ds-bot') -Arguments @('run', 'harness') }
    catch { Fail "harness install failed: the DSH packages for the unit tests could not be fetched. Check network/registry access, or re-run with -WithoutHarness to skip test-only packages." }
}

if ($PluginOnly) {
    Write-Host "setup: skipping desktop app packages (-PluginOnly)"
} else {
    Write-Host "setup: desktop app packages"
    try { Invoke-Npm -Directory (Join-Path $root 'app') -Arguments @('ci', '--no-fund', '--no-audit') }
    catch { Fail "app npm ci failed. The app lockfile needs npm 11; if npm reported an out-of-sync lockfile, upgrade npm and re-run. For packaging, Electron archives download through electron-builder's cache; set ELECTRON_MIRROR if that download is blocked." }
}

Write-Host "setup: verifying client.js matches src/client"
Push-Location (Join-Path $root 'ds-bot')
try {
    node scripts/build-client.mjs --check
    if ($LASTEXITCODE -ne 0) { throw "build-client --check exited $LASTEXITCODE." }
} catch {
    Fail "client.js is stale or does not match src/client. Run 'npm run build' in ds-bot/ and commit the regenerated bundle."
} finally {
    Pop-Location
}

Write-Host "setup: done"
