#!/bin/sh
# Installs everything a checkout that has never installed anything needs to build and test.
#
#   sh scripts/setup.sh                 # full setup: plugin, link, app deps, generated bundles
#   sh scripts/setup.sh --plugin-only   # skip the desktop app's dependencies
#   sh scripts/setup.sh --without-harness
#
# Installs from the lockfiles:
#   ds-bot/node_modules   the build tools (esbuild), for client.js and link.js
#   link/node_modules     the phone link's packages; build-link.mjs bundles ../link/src
#   ds-bot/dev/harness    the DSH packages the unit tests and the linter load (skip with --without-harness)
#   app/node_modules      the desktop app's packages (skip with --plugin-only)
#
# After the installs it regenerates ds-bot/client.js and ds-bot/link.js from src/client and
# src/link, then checks that the committed client.js matches a fresh build.
#
# Requirements: Node.js 22.19 or later (Node 24 recommended), npm 11 or later, Git. The app
# lockfile was generated by npm 11; npm 10 rejects it with an out-of-sync error. On Linux the
# native test dependencies need build-essential and python3; on macOS the Xcode Command Line
# Tools. Repeating the script is safe: npm ci rebuilds the node_modules trees from the lockfiles.
set -eu

usage() {
    cat <<'EOF'
Usage: sh scripts/setup.sh [--plugin-only] [--without-harness]

  --plugin-only      Skip the desktop app's dependencies (plugin/DSH usage only).
  --without-harness  Skip the DSH test harness packages in ds-bot/dev/harness.

Proxy: npm and the Electron download honor npm_config_proxy / npm_config_https_proxy and the
ELECTRON_MIRROR / ELECTRON_BUILDER_BINARIES_MIRROR environment variables; export them before
running this script if your network needs a mirror.
EOF
}

with_harness=1
plugin_only=0
for arg in "$@"; do
    case "$arg" in
        --without-harness) with_harness=0 ;;
        --plugin-only) plugin_only=1 ;;
        -h | --help) usage; exit 0 ;;
        *) echo "setup: unknown option: $arg" >&2; usage >&2; exit 2 ;;
    esac
done

fail() {
    echo "setup: $*" >&2
    exit 1
}

# version_ge MIN CUR: 0 when CUR >= MIN, 1 otherwise (dotted major.minor versions)
version_ge() {
    min_major=${1%%.*}
    rest=${1#*.}
    min_minor=${rest%%.*}
    cur_major=${2%%.*}
    rest=${2#*.}
    cur_minor=${rest%%.*}
    [ "$cur_major" -gt "$min_major" ] && return 0
    [ "$cur_major" -eq "$min_major" ] && [ "${cur_minor:-0}" -ge "${min_minor:-0}" ]
}

command -v node >/dev/null 2>&1 || fail "Node.js is not installed or not on PATH. Install Node.js 22.19 or later (Node 24 recommended), for example with nvm or fnm, then re-run this script."
command -v npm >/dev/null 2>&1 || fail "npm is not installed or not on PATH. It ships with Node.js; reinstall Node.js 22.19 or later."
command -v git >/dev/null 2>&1 || fail "Git is not installed or not on PATH."

node_version="$(node -p 'process.versions.node')"
npm_version="$(npm -v)"
npm_major="$(printf '%s' "$npm_version" | cut -d. -f1)"

version_ge 22.19 "$node_version" || fail "Node $node_version is too old. This checkout needs Node.js 22.19 or later (Node 24 recommended); switch with nvm/fnm and re-run."
[ "$npm_major" -ge 11 ] 2>/dev/null || fail "npm $npm_version is too old. The app lockfile was generated by npm 11: upgrade Node.js to 24 (which ships npm 11), or run 'npm install -g npm@11', then re-run."

case "$node_version" in
    22.*) echo "setup: note: Node 22 is supported by CI; the pinned DSH runtime declares Node >=24.9.0 and prints an EBADENGINE warning on Node 22." ;;
esac

# Platform toolchain hints. These do not block: unit tests can run without native compilation,
# but a missing C toolchain surfaces later as a node-pty / koffi build failure.
case "$(uname -s 2>/dev/null || echo unknown)" in
    Darwin)
        if ! xcode-select -p >/dev/null 2>&1; then
            echo "setup: warning: Xcode Command Line Tools are not installed. Run 'xcode-select --install' if a native module fails to build." >&2
        fi
        ;;
    Linux)
        command -v cc >/dev/null 2>&1 || echo "setup: warning: no C compiler on PATH. On Debian/Ubuntu run 'sudo apt-get install build-essential python3'." >&2
        command -v python3 >/dev/null 2>&1 || echo "setup: warning: python3 is missing; node-gyp needs it. On Debian/Ubuntu run 'sudo apt-get install python3 build-essential'." >&2
        ;;
esac

root="$(git rev-parse --show-toplevel)"
cd "$root"

echo "setup: ds-bot build tools"
(cd ds-bot && npm ci --no-fund --no-audit) || fail "ds-bot npm ci failed. Check the npm/registry output above; a proxy or mirror issue usually shows here."

echo "setup: phone link packages"
npm ci --no-fund --no-audit --prefix link || fail "link npm ci failed. Check the npm/registry output above."

echo "setup: regenerate client.js and link.js"
(cd ds-bot && npm run build) || fail "ds-bot build failed (esbuild). Re-run after fixing the reported src/client or src/link error."

if [ "$with_harness" -eq 1 ]; then
    echo "setup: DSH test harness packages"
    (cd ds-bot && npm run harness) || fail "harness install failed: the DSH packages for the unit tests could not be fetched. Check network/registry access, or re-run with --without-harness to skip test-only packages."
else
    echo "setup: skipping DSH test harness (--without-harness)"
fi

if [ "$plugin_only" -eq 0 ]; then
    echo "setup: desktop app packages"
    (cd app && npm ci --no-fund --no-audit) || fail "app npm ci failed. The app lockfile needs npm 11; if npm reported an out-of-sync lockfile, upgrade npm and re-run. For packaging, Electron archives download through electron-builder's cache; set ELECTRON_MIRROR if that download is blocked."
else
    echo "setup: skipping desktop app packages (--plugin-only)"
fi

echo "setup: verifying client.js matches src/client"
(cd ds-bot && node scripts/build-client.mjs --check) || fail "client.js is stale or does not match src/client. Run 'npm run build' in ds-bot/ and commit the regenerated bundle."

echo "setup: done"
